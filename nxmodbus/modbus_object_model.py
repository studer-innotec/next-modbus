    def get_prop_type(self, slave_id, address):
        """
        Get the type of given property from a property id.

        Parameters
        ----------
        slave_id: int
            Slave identifier number (targeted device)
        address: int
            Register starting address, see "Technical specification - Next Modbus appendix" for
            the complete list of accessible register per device
        Returns
        -------
        prop_type: PropType
            The property type from nxmodbus/proptypes.py or `None` if not found.
        """
        modbus_start_address = slave_id
        prop_type = None
        for i in range(len(self.objects) - 1):
            current_object = self.objects[i]
            next_object = self.objects[i + 1]
            if current_object.modbus_device_start_address < modbus_start_address < \
                    next_object.modbus_device_start_address:
                for prop in current_object.props:
                    if prop.address == address:
                        prop_type = prop.type
        return prop_type

    @staticmethod
    def get_prop_size(slave_id, prop_type, string_size=0):
        """

        Parameters
        ----------
        slave_id
        prop_type
        string_size

        Returns
        -------

        """
        if string_size % 2 == 0:
            size = int(string_size / 2)
        else:
            size = int(string_size / 2) + 1
        if prop_type == PropType.BOOL:
            size = 1
        elif prop_type == PropType.INT or \
                prop_type == PropType.UINT or \
                prop_type == PropType.FLOAT or \
                prop_type == PropType.ENUM or \
                prop_type == PropType.BITFIELD:
            size = 2
        elif prop_type == PropType.INT64 or \
                prop_type == PropType.UINT64 or \
                prop_type == PropType.FLOAT64:
            size = 4
        return size

    def check_versions(self, current_omv_major, current_omv_minor):
        """
        Checks the compatibility of the provided Object Model Version (OMV) major and minor with local definitions.

        Parameters
        ----------
        current_omv_major: int
                Major Object Model Version read from the device.
        current_omv_minor:
                Minor Object Model Version read from the device.
        Returns
        -------
        tuple of bool
            A tuple containing:
            - A boolean indicating whether the major version corresponds to the Modbus Object Model.
            - A boolean indicating whether the minor version corresponds to the Modbus Object Model.
        """
        return current_omv_major == self.version_major, current_omv_minor == self.version_minor
